#!/usr/bin/env bash
# Idempotent per-worktree setup: pinned tools, JS deps, an isolated Postgres (own compose project, own
# volume, own ports), migrations applied, and .env.local (gitignored) for every other command to source,
# with the ports of the opt-in observability stack (make obs-up) reserved in the same block.
# Ports and project name derive from the worktree path, are checked against listening sockets and against
# every other worktree's .env.local, and are reused on re-runs.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
# shellcheck source=tool-versions.env
source scripts/tool-versions.env
# shellcheck source=harness/layout.sh
source scripts/harness/layout.sh || exit 2
# OBS_IMAGE: compose interpolates every service, the inactive obs profile too.
export GOTOOLCHAIN="$GO_TOOLCHAIN" PATH="$ROOT/.bin:$ROOT/node_modules/.bin:$PATH" OBS_IMAGE
ENV_FILE="$ROOT/.env.local"

log() { echo "setup-worktree: $*" >&2; }

# --- identity + ports ---------------------------------------------------------------------------------
hash="$(printf '%s' "$ROOT" | shasum -a 256 | cut -c1-8)"
slug="$(basename "$ROOT" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9\n' '-' | cut -c1-20)"
project="harness-${slug}-${hash}"

# A block is 10 ports; offsets 0..7 are in use: DB, API, WEB, then the obs profile's OTLP (+3), LOKI (+4),
# PROMETHEUS (+5), TEMPO (+6) and GRAFANA (+7) (ADR 0017).
BLOCK_USED=8
port_in_use() { lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1; }
reserved_ports() { # ports claimed by other worktrees of this repo: every *_PORT in their .env.local
  git worktree list --porcelain 2>/dev/null | awk '/^worktree /{sub(/^worktree /, ""); print}' | while IFS= read -r wt; do
    [[ "$wt" == "$ROOT" || ! -f "$wt/.env.local" ]] && continue
    grep -E '^[A-Z_]+_PORT=' "$wt/.env.local" | cut -d= -f2
  done
}

# Reused only when it is this worktree's and already has the obs ports; an older file is rewritten.
if [[ -f "$ENV_FILE" ]] && grep -q "^COMPOSE_PROJECT_NAME=$project$" "$ENV_FILE" && grep -q '^GRAFANA_PORT=' "$ENV_FILE"; then
  log "reusing $ENV_FILE"
  # shellcheck source=/dev/null # generated per worktree
  source "$ENV_FILE"
else
  reserved=" $(reserved_ports | tr '\n' ' ') "
  base=$((20000 + (16#$hash % 2000) * 10))
  own=" " # ports this worktree's own containers may already listen on
  old=""
  if [[ -f "$ENV_FILE" ]] && grep -q "^COMPOSE_PROJECT_NAME=$project$" "$ENV_FILE"; then
    old="$(grep -E '^DB_PORT=[0-9]+$' "$ENV_FILE" | cut -d= -f2 || true)"
    if [[ -n "$old" ]]; then # keep the block an older setup chose, if its new offsets are free
      base=$old
      own=" $(grep -E '^[A-Z_]+_PORT=' "$ENV_FILE" | cut -d= -f2 | tr '\n' ' ') "
    fi
  fi
  for _ in $(seq 1 200); do
    ok=1
    for ((p = base; p < base + BLOCK_USED; p++)); do
      [[ "$own" == *" $p "* ]] && continue
      if port_in_use "$p" || [[ "$reserved" == *" $p "* ]]; then
        ok=0
        break
      fi
    done
    ((ok)) && break
    base=$((base + 10))
    ((base > 39990)) && base=20000
  done
  ((ok)) || {
    log "no free port block found in 20000-39999"
    exit 1
  }
  DB_PORT=$base API_PORT=$((base + 1)) WEB_PORT=$((base + 2))
  OTLP_PORT=$((base + 3)) LOKI_PORT=$((base + 4)) PROMETHEUS_PORT=$((base + 5)) TEMPO_PORT=$((base + 6))
  GRAFANA_PORT=$((base + 7))
  # Telemetry goes to this worktree's collector (make obs-up); make dev turns it off while none listens.
  # A 5 s metric interval (SDK default 60 s) lets make metrics see a request within seconds.
  cat >"$ENV_FILE" <<EOF
# Generated by scripts/setup-worktree.sh for $ROOT — local only, never commit.
COMPOSE_PROJECT_NAME=$project
POSTGRES_IMAGE=$POSTGRES_IMAGE
DB_PORT=$DB_PORT
API_PORT=$API_PORT
WEB_PORT=$WEB_PORT
OTLP_PORT=$OTLP_PORT
LOKI_PORT=$LOKI_PORT
PROMETHEUS_PORT=$PROMETHEUS_PORT
TEMPO_PORT=$TEMPO_PORT
GRAFANA_PORT=$GRAFANA_PORT
DATABASE_URL=postgres://app:app@127.0.0.1:$DB_PORT/app?sslmode=disable
HTTP_ADDR=127.0.0.1:$API_PORT
AUTH_MODE=dev-stub
LOG_LEVEL=debug
OTEL_TRACES_EXPORTER=otlp
OTEL_METRICS_EXPORTER=otlp
OTEL_LOGS_EXPORTER=otlp
OTEL_EXPORTER_OTLP_ENDPOINT=http://127.0.0.1:$OTLP_PORT
OTEL_METRIC_EXPORT_INTERVAL=5000
EOF
  if [[ -n "$old" ]]; then
    log "rewrote $ENV_FILE (added obs ports; hand edits are lost)"
    [[ "$base" == "$old" ]] || log "port block moved from $old to $base (a port of the old block is taken)"
  fi
  log "wrote $ENV_FILE (db :$DB_PORT, api :$API_PORT, web :$WEB_PORT, obs :$OTLP_PORT-:$GRAFANA_PORT)"
fi

# --- tools + deps -------------------------------------------------------------------------------------
make --no-print-directory tools deps

# --- git hooks ----------------------------------------------------------------------------------------
# pre-commit scans the staged content for secrets and runs the cheap per-file sensors on it
# (scripts/harness/pre-commit.sh); commit-msg checks Conventional Commits locally
# (rules.md#git-conventional-commits). Never replaces a hooks path someone else set (husky, lefthook, ...).
hooks="$(git config --get core.hooksPath || true)"
if [[ -z "$hooks" || "$hooks" == scripts/git-hooks ]]; then
  git config core.hooksPath scripts/git-hooks
else
  log "core.hooksPath is '$hooks': not installing scripts/git-hooks (make check and make commits still run their checks)"
fi

# --- database -----------------------------------------------------------------------------------------
if ! harness_stack_has db; then
  log "STACK=$STACK has no db: not starting Postgres"
  exit 0
fi
if [[ "${SKIP_DB:-0}" == 1 ]]; then
  log "SKIP_DB=1: not starting Postgres"
  exit 0
fi
if ! { command -v docker >/dev/null && docker info >/dev/null 2>&1; }; then
  log "Docker is not running (needed for Postgres). Start it or use SKIP_DB=1."
  exit 1
fi
docker compose --progress quiet --env-file "$ENV_FILE" up -d --wait db >/dev/null
(
  set -a
  # shellcheck source=/dev/null # generated per worktree
  source "$ENV_FILE"
  set +a
  cd "$API_DIR" && atlas migrate apply --env local >/dev/null
)
log "ready: project $project, DATABASE_URL in .env.local"
