#!/usr/bin/env bash
# Idempotent per-worktree setup: pinned tools, JS deps, an isolated Postgres (own compose project, own
# volume, own ports), migrations applied, and .env.local (gitignored) for every other command to source.
# Ports and project name derive from the worktree path, are checked against listening sockets and against
# every other worktree's .env.local, and are reused on re-runs.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
# shellcheck source=tool-versions.env
source scripts/tool-versions.env
export GOTOOLCHAIN="$GO_TOOLCHAIN" PATH="$ROOT/.bin:$ROOT/node_modules/.bin:$PATH"
ENV_FILE="$ROOT/.env.local"

log() { echo "setup-worktree: $*" >&2; }

# --- identity + ports ---------------------------------------------------------------------------------
hash="$(printf '%s' "$ROOT" | shasum -a 256 | cut -c1-8)"
slug="$(basename "$ROOT" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9\n' '-' | cut -c1-20)"
project="harness-${slug}-${hash}"

port_in_use() { lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1; }
reserved_ports() { # ports claimed by other worktrees of this repo
  git worktree list --porcelain 2>/dev/null | awk '/^worktree /{print $2}' | while read -r wt; do
    [[ "$wt" == "$ROOT" || ! -f "$wt/.env.local" ]] && continue
    grep -E '^(DB|API|WEB)_PORT=' "$wt/.env.local" | cut -d= -f2
  done
}

if [[ -f "$ENV_FILE" ]] && grep -q "^COMPOSE_PROJECT_NAME=$project$" "$ENV_FILE"; then
  log "reusing $ENV_FILE"
  # shellcheck source=/dev/null # generated per worktree
  source "$ENV_FILE"
else
  reserved=" $(reserved_ports | tr '\n' ' ') "
  base=$((20000 + (16#$hash % 2000) * 10))
  for _ in $(seq 1 200); do
    ok=1
    for p in "$base" $((base + 1)) $((base + 2)); do
      if port_in_use "$p" || [[ "$reserved" == *" $p "* ]]; then
        ok=0
        break
      fi
    done
    ((ok)) && break
    base=$((base + 10))
    ((base > 39990)) && base=20000
  done
  ((ok)) || {
    log "no free port block found in 20000-39999"
    exit 1
  }
  DB_PORT=$base API_PORT=$((base + 1)) WEB_PORT=$((base + 2))
  cat >"$ENV_FILE" <<EOF
# Generated by scripts/setup-worktree.sh for $ROOT — local only, never commit.
COMPOSE_PROJECT_NAME=$project
POSTGRES_IMAGE=$POSTGRES_IMAGE
DB_PORT=$DB_PORT
API_PORT=$API_PORT
WEB_PORT=$WEB_PORT
DATABASE_URL=postgres://app:app@127.0.0.1:$DB_PORT/app?sslmode=disable
HTTP_ADDR=127.0.0.1:$API_PORT
AUTH_MODE=dev-stub
LOG_LEVEL=debug
OTEL_TRACES_EXPORTER=none
EOF
  log "wrote $ENV_FILE (db :$DB_PORT, api :$API_PORT, web :$WEB_PORT)"
fi

# --- tools + deps -------------------------------------------------------------------------------------
make --no-print-directory tools deps

# --- git hooks ----------------------------------------------------------------------------------------
# commit-msg checks Conventional Commits locally (rules.md#git-conventional-commits). Never replaces a
# hooks path someone else set (husky, lefthook, ...).
hooks="$(git config --get core.hooksPath || true)"
if [[ -z "$hooks" || "$hooks" == scripts/git-hooks ]]; then
  git config core.hooksPath scripts/git-hooks
else
  log "core.hooksPath is '$hooks': not installing scripts/git-hooks (make commits still checks commit messages)"
fi

# --- database -----------------------------------------------------------------------------------------
if [[ "${SKIP_DB:-0}" == 1 ]]; then
  log "SKIP_DB=1: not starting Postgres"
  exit 0
fi
if ! { command -v docker >/dev/null && docker info >/dev/null 2>&1; }; then
  log "Docker is not running (needed for Postgres). Start it or use SKIP_DB=1."
  exit 1
fi
docker compose --progress quiet --env-file "$ENV_FILE" up -d --wait db >/dev/null
(
  set -a
  # shellcheck source=/dev/null # generated per worktree
  source "$ENV_FILE"
  set +a
  cd apps/api && atlas migrate apply --env local >/dev/null
)
log "ready: project $project, DATABASE_URL in .env.local"
