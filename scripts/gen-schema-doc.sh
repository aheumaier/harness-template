#!/usr/bin/env bash
# Writes docs/generated/db-schema.md from the schema produced by replaying all migrations on a
# throwaway Docker Postgres (Atlas dev database). Needs Docker. Never edit the output by hand.
#   gen-schema-doc.sh          regenerate
#   gen-schema-doc.sh --check  offline staleness check: the doc's stamp must equal atlas.sum's hash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
API="$ROOT/apps/api"; OUT="$ROOT/docs/generated/db-schema.md"
sum="$(head -1 "$API/db/migrations/atlas.sum")"

if [[ "${1:-}" == "--check" ]]; then
  stamp="$(sed -n 's/^<!-- migrations: \(.*\) -->$/\1/p' "$OUT" 2>/dev/null || true)"
  if [[ "$stamp" != "$sum" ]]; then
    echo "docs/generated/db-schema.md is stale [db-schema-doc-fresh]: generated for '${stamp:-<missing>}', migrations are '$sum'." >&2
    exit 1
  fi
  exit 0
fi

cd "$API"
inspect() { atlas schema inspect --url file://db/migrations --dev-url "docker://postgres/17/dev" --format "$1" 2>/dev/null; }
{
  echo "# Database schema"
  echo
  echo "<!-- GENERATED by \`make gen-schema-doc\` from apps/api/db/migrations. DO NOT EDIT. -->"
  echo "<!-- migrations: $sum -->"
  echo
  er="$(inspect '{{ mermaid . }}')"
  if [[ "$(echo "$er" | wc -l)" -gt 1 ]]; then printf '```mermaid\n%s\n```\n\n' "$er"; else echo "_No tables yet._"; echo; fi
  echo '```sql'
  inspect '{{ sql . "  " }}'
  echo '```'
} >"$OUT.tmp"
mv "$OUT.tmp" "$OUT"
